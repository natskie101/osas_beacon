-- BEACON OSAS Portal — users and access control.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(20) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(190) NOT NULL,
    username VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role ENUM('Coordinator', 'Administrator', 'Student') NOT NULL DEFAULT 'Student',
    student_id VARCHAR(30) NULL,
    department VARCHAR(150) NULL,
    program VARCHAR(150) NULL,
    year_level VARCHAR(30) NULL,
    access_level VARCHAR(150) NULL,
    account_tier ENUM('Student Tier', 'Admin Tier') NOT NULL DEFAULT 'Student Tier',
    status ENUM('Active', 'Pending', 'Inactive') NOT NULL DEFAULT 'Pending',
    phone VARCHAR(30) NULL,
    school_id_file_id BIGINT UNSIGNED NULL,
    email_verified_at DATETIME NULL,
    last_login_at DATETIME NULL,
    last_seen_at DATETIME NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    requested_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY users_public_id_unique (public_id),
    UNIQUE KEY users_email_unique (email),
    UNIQUE KEY users_username_unique (username),
    KEY users_role_index (role),
    KEY users_status_index (status),
    KEY users_last_name_index (last_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
