-- Content, service and reporting modules for the BEACON OSAS Portal.

CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(30) NOT NULL,
    title VARCHAR(200) NOT NULL,
    category VARCHAR(100) NOT NULL DEFAULT '',
    audience VARCHAR(100) NOT NULL DEFAULT 'All Student Portals',
    status ENUM('Draft', 'Scheduled', 'Published', 'Archived') NOT NULL DEFAULT 'Draft',
    priority VARCHAR(50) NOT NULL DEFAULT 'Standard Priority',
    summary TEXT NULL,
    body LONGTEXT NULL,
    author VARCHAR(150) NOT NULL DEFAULT '',
    views BIGINT UNSIGNED NOT NULL DEFAULT 0,
    published_at DATETIME NULL,
    scheduled_for DATETIME NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY announcements_public_id_unique (public_id),
    KEY announcements_status_index (status),
    KEY announcements_category_index (category),
    KEY announcements_published_index (published_at),
    CONSTRAINT announcements_creator_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS regulations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(30) NOT NULL,
    reference_code VARCHAR(50) NOT NULL DEFAULT '',
    title VARCHAR(200) NOT NULL,
    category VARCHAR(100) NOT NULL DEFAULT '',
    audience VARCHAR(100) NOT NULL DEFAULT 'All Students',
    status ENUM('Draft', 'Pending Review', 'Published', 'Archived') NOT NULL DEFAULT 'Draft',
    effective_date VARCHAR(100) NOT NULL DEFAULT '',
    review_schedule VARCHAR(150) NOT NULL DEFAULT '',
    approval_body VARCHAR(200) NOT NULL DEFAULT '',
    views BIGINT UNSIGNED NOT NULL DEFAULT 0,
    summary TEXT NULL,
    body LONGTEXT NULL,
    sanctions JSON NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY regulations_public_id_unique (public_id),
    KEY regulations_status_index (status),
    KEY regulations_category_index (category),
    CONSTRAINT regulations_creator_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS orientation_modules (
