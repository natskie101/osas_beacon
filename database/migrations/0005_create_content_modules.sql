    CONSTRAINT lost_found_items_creator_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS lost_found_claims (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(30) NOT NULL,
    item_id BIGINT UNSIGNED NOT NULL,
    claimant_user_id BIGINT UNSIGNED NULL,
    claimant_name VARCHAR(150) NOT NULL,
    claimant_email VARCHAR(190) NOT NULL,
    student_id VARCHAR(30) NOT NULL DEFAULT '',
    proof TEXT NULL,
    message TEXT NULL,
    attachment VARCHAR(255) NOT NULL DEFAULT '',
    status ENUM('Pending', 'Verified', 'Rejected') NOT NULL DEFAULT 'Pending',
    verified_by VARCHAR(150) NOT NULL DEFAULT '',
    verified_at DATETIME NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY lost_found_claims_public_id_unique (public_id),
    KEY lost_found_claims_item_index (item_id, status),
    CONSTRAINT lost_found_claims_item_fk FOREIGN KEY (item_id) REFERENCES lost_found_items (id) ON DELETE CASCADE,
    CONSTRAINT lost_found_claims_user_fk FOREIGN KEY (claimant_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

