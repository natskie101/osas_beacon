CREATE TABLE IF NOT EXISTS lost_found_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(30) NOT NULL,
    type ENUM('Lost', 'Found') NOT NULL DEFAULT 'Found',
    title VARCHAR(200) NOT NULL,
    category VARCHAR(100) NOT NULL DEFAULT '',
    description TEXT NULL,
    location VARCHAR(180) NOT NULL DEFAULT '',
    date_occurred DATETIME NULL,
    reported_by VARCHAR(150) NOT NULL DEFAULT '',
    reporter_email VARCHAR(190) NOT NULL DEFAULT '',
    student_id VARCHAR(30) NOT NULL DEFAULT '',
    contact VARCHAR(190) NOT NULL DEFAULT '',
    status ENUM('Open', 'Claim Pending', 'Unclaimed', 'Returned', 'Archived', 'Closed') NOT NULL DEFAULT 'Open',
    custody VARCHAR(150) NOT NULL DEFAULT '',
    attachment VARCHAR(255) NOT NULL DEFAULT '',
    posted_at DATETIME NOT NULL,
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY lost_found_items_public_id_unique (public_id),
    KEY lost_found_items_status_index (status),
